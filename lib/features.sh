# Feature flag helpers shared by install.sh.
# Sourced; do not execute directly.

# Defaults when a host has no features.conf yet.
features_set_defaults() {
  CLI_bat=true
  CLI_btop=true
  CLI_duti=true
  CLI_eza=true
  CLI_fd=true
  CLI_fzf=true
  CLI_gh=true
  CLI_git=true
  CLI_ncdu=true
  CLI_ripgrep=true
  CLI_starship=true
  CLI_tldr=true
  CLI_uv=true
  CLI_zoxide=true
  CLI_yazi=true

  RICE_omniwm=true
  RICE_sketchybar=true
  RICE_jankyborders=true
  RICE_skhd=true
  RICE_ghostty=true

  APPS_cursor=true
  APPS_sublimeText=true
  APPS_teamviewer=false
  APPS_transmission=true
  APPS_iina=true
  APPS_libreoffice=true
  APPS_geForceNow=false
}

# Load KEY=value pairs from a features.conf (safe: only known keys).
features_load() {
  local file="$1"
  features_set_defaults
  [[ -f "$file" ]] || return 0

  local line key val
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ -z "$line" || "$line" == \#* ]] && continue
    key="${line%%=*}"
    val="${line#*=}"
    case "$key" in
      CLI_bat|CLI_btop|CLI_duti|CLI_eza|CLI_fd|CLI_fzf|CLI_gh|CLI_git|CLI_ncdu|CLI_ripgrep|CLI_starship|CLI_tldr|CLI_uv|CLI_zoxide|CLI_yazi|\
      RICE_omniwm|RICE_sketchybar|RICE_jankyborders|RICE_skhd|RICE_ghostty|\
      APPS_cursor|APPS_sublimeText|APPS_teamviewer|APPS_transmission|APPS_iina|APPS_libreoffice|APPS_geForceNow)
        eval "$key=$([[ "$val" == "true" ]] && echo true || echo false)"
        ;;
    esac
  done <"$file"
}

