# Echo brew formulae / casks / stow package names based on current flags.
features_brew_formulae() {
  local -a out=()
  out+=(stow gum jq)
  out+=(zsh-autosuggestions zsh-syntax-highlighting zsh-completions)
  $CLI_bat && out+=(bat)
  $CLI_btop && out+=(btop)
  $CLI_duti && out+=(duti)
  $CLI_eza && out+=(eza)
  $CLI_fd && out+=(fd)
  $CLI_fzf && out+=(fzf)
  $CLI_gh && out+=(gh)
  $CLI_git && out+=(git)
  $CLI_ncdu && out+=(ncdu)
  $CLI_ripgrep && out+=(ripgrep)
  $CLI_starship && out+=(starship)
  $CLI_tldr && out+=(tldr)
  $CLI_uv && out+=(uv)
  $CLI_zoxide && out+=(zoxide)
  $CLI_yazi && out+=(yazi)
  $RICE_sketchybar && out+=(sketchybar)
  $RICE_jankyborders && out+=(borders)
  $RICE_skhd && out+=(skhd)
  print -r -- "${out[@]}"
}

